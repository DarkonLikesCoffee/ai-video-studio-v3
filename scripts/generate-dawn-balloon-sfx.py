#!/usr/bin/env python3
"""Render deterministic DawnBalloon sound effects with Earshot."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
out = root / "public/audio/sfx"
out.mkdir(parents=True, exist_ok=True)
cues = [
    {"id":"lift-off","file":"lift-off.wav","sound":"whoosh/soft","words":"a gentle warm breath of air as a hot-air balloon begins to lift, soft and organic","event":1.0,"volume":0.34,"duration":1.0},
    {"id":"ridge-transition","file":"ridge-transition.wav","sound":"whoosh/sweep","words":"a restrained airy cinematic sweep, soft high air, no impact","event":6.4,"volume":0.24,"duration":0.9},
    {"id":"cloud-transition","file":"cloud-transition.wav","sound":"whoosh/sweep","words":"a delicate airy rising sweep for a calm scene transition, no heavy hit","event":12.8,"volume":0.20,"duration":0.9},
    {"id":"basket-cloth","file":"basket-cloth.wav","sound":"cloth/flag","words":"light cloth fluttering and gently moving in a steady breeze","event":14.2,"volume":0.14,"duration":0.8},
]
manifest = []
for cue in cues:
    target = out / cue["file"]
    command = ["earshot","make",cue["words"],"-o",str(target),"--sound",cue["sound"],"--dur",str(cue["duration"]),"--seed","17","--json"]
    result = subprocess.run(command, check=True, text=True, capture_output=True)
    try:
        data = json.loads(result.stdout)
    except json.JSONDecodeError:
        data = {}
    take = (data.get("takes") or [{}])[0]
    peak = float(take.get("peak_s", 0.0))
    manifest.append({"id":cue["id"],"src":"/audio/sfx/"+cue["file"],"startSeconds":round(max(0,cue["event"]-peak),4),"eventSeconds":cue["event"],"peakSeconds":peak,"volume":cue["volume"],"sound":cue["sound"],"summary":take.get("summary",result.stdout.strip().splitlines()[0] if result.stdout else "")})
source = "// Generated by scripts/generate-dawn-balloon-sfx.py. Do not edit by hand.\n"
source += "export const dawnBalloonSfx = " + json.dumps(manifest, indent=2) + " as const;\n"
(root/"src/generated/dawn-balloon-sfx.ts").write_text(source,encoding="utf-8")
print(json.dumps(manifest,indent=2))
